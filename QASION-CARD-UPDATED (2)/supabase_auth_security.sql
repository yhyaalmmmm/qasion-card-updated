-- QASION CARD: Auth + profile + security events (Supabase)
-- Run this in Supabase SQL Editor before enabling production login.

create table if not exists public.qc_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  phone text,
  country text,
  age integer,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.qc_security_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  event_type text not null,
  device text,
  created_at timestamptz not null default now()
);

create table if not exists public.qc_devices (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  device_name text,
  device_fingerprint text,
  last_seen_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  unique(user_id, device_fingerprint)
);

alter table public.qc_profiles enable row level security;
alter table public.qc_security_events enable row level security;
alter table public.qc_devices enable row level security;

revoke all on public.qc_profiles from anon;
revoke all on public.qc_security_events from anon;
revoke all on public.qc_devices from anon;
grant select, insert, update on public.qc_profiles to authenticated;
grant select, insert on public.qc_security_events to authenticated;
grant select, insert, update on public.qc_devices to authenticated;

create policy "qc_profiles_select_own" on public.qc_profiles for select to authenticated using (auth.uid() = id);
create policy "qc_profiles_insert_own" on public.qc_profiles for insert to authenticated with check (auth.uid() = id);
create policy "qc_profiles_update_own" on public.qc_profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

create policy "qc_security_select_own" on public.qc_security_events for select to authenticated using (auth.uid() = user_id);
create policy "qc_security_insert_own" on public.qc_security_events for insert to authenticated with check (auth.uid() = user_id);

create policy "qc_devices_select_own" on public.qc_devices for select to authenticated using (auth.uid() = user_id);
create policy "qc_devices_insert_own" on public.qc_devices for insert to authenticated with check (auth.uid() = user_id);
create policy "qc_devices_update_own" on public.qc_devices for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

create or replace function public.qc_handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.qc_profiles (id, full_name, phone, country, age)
  values (
    new.id,
    nullif(new.raw_user_meta_data->>'full_name',''),
    nullif(new.raw_user_meta_data->>'phone',''),
    nullif(new.raw_user_meta_data->>'country',''),
    nullif(new.raw_user_meta_data->>'age','')::integer
  )
  on conflict (id) do update set
    full_name = excluded.full_name,
    phone = excluded.phone,
    country = excluded.country,
    age = excluded.age,
    updated_at = now();
  return new;
end;
$$;

drop trigger if exists qc_on_auth_user_created on auth.users;
create trigger qc_on_auth_user_created
after insert on auth.users
for each row execute function public.qc_handle_new_user();

