-- Telegram account linking (no SMS required)
create table if not exists public.qc_telegram_links (
  user_id uuid primary key references auth.users(id) on delete cascade,
  telegram_id text not null unique,
  username text,
  first_name text,
  last_name text,
  photo_url text,
  linked_at timestamptz not null default now()
);

alter table public.qc_telegram_links enable row level security;
